#include "installer.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include <sys/stat.h>

int installer_net_generate_configs(const net_interface_profile_t* net, const char* hostname, const char* root_mount) {
    if (!net || !hostname || !root_mount) return -1;

    char etc_dir[512];
    snprintf(etc_dir, sizeof(etc_dir), "%s/etc", root_mount);
    mkdir(etc_dir, 0755);

    char path[512];

    /* 1. Write /etc/hostname */
    snprintf(path, sizeof(path), "%s/etc/hostname", root_mount);
    FILE* f_host = fopen(path, "w");
    if (f_host) {
        fprintf(f_host, "%s\n", hostname);
        fclose(f_host);
    }

    /* 2. Write /etc/hosts */
    snprintf(path, sizeof(path), "%s/etc/hosts", root_mount);
    FILE* f_hosts = fopen(path, "w");
    if (f_hosts) {
        fprintf(f_hosts,
            "127.0.0.1   localhost\n"
            "127.0.1.1   %s\n"
            "::1         localhost ip6-localhost ip6-loopback\n"
            "ff02::1     ip6-allnodes\n"
            "ff02::2     ip6-allrouters\n",
            hostname);
        fclose(f_hosts);
    }

    /* 3. Write /etc/network.conf */
    snprintf(path, sizeof(path), "%s/etc/network.conf", root_mount);
    FILE* f_net = fopen(path, "w");
    if (f_net) {
        fprintf(f_net,
            "# ==============================================================================\n"
            "# LastKernel Enterprise Network Profile\n"
            "# ==============================================================================\n"
            "HOSTNAME=\"%s\"\n"
            "INTERFACE=\"%s\"\n"
            "MAC_ADDR=\"%s\"\n"
            "CONFIG_MODE=\"%s\"\n"
            "IP_ADDR=\"%s\"\n"
            "GATEWAY=\"%s\"\n"
            "PRIMARY_DNS=\"%s\"\n"
            "SECONDARY_DNS=\"%s\"\n"
            "VLAN_ID=%u\n"
            "BOND_MODE=%u\n"
            "RSS_MULTI_QUEUE=%d\n"
            "BBRV3_CONGESTION=%d\n",
            hostname,
            net->ifname[0] ? net->ifname : "eth0",
            net->mac_address[0] ? net->mac_address : "auto",
            net->mode == NET_MODE_DHCP ? "dhcp" : "static",
            net->ip_address[0] ? net->ip_address : "10.0.2.15/24",
            net->gateway[0] ? net->gateway : "10.0.2.2",
            net->primary_dns[0] ? net->primary_dns : "1.1.1.1",
            net->secondary_dns[0] ? net->secondary_dns : "8.8.8.8",
            net->vlan_id,
            (unsigned int)net->bond_mode,
            net->enable_rss_multi_queue ? 1 : 0,
            net->enable_bbrv3 ? 1 : 0);
        fclose(f_net);
    }

    /* 4. Write /etc/resolv.conf */
    snprintf(path, sizeof(path), "%s/etc/resolv.conf", root_mount);
    FILE* f_res = fopen(path, "w");
    if (f_res) {
        fprintf(f_res,
            "# Generated by LastKernel Installer\n"
            "nameserver %s\n"
            "nameserver %s\n"
            "options edns0 trust-ad\n",
            net->primary_dns[0] ? net->primary_dns : "1.1.1.1",
            net->secondary_dns[0] ? net->secondary_dns : "8.8.8.8");
        fclose(f_res);
    }

    return 0;
}
